create policy "authenticated users can read articles"
  on public.articles for select to authenticated using (true);
create policy "authenticated users can read article celltypes"
  on public.article_celltypes for select to authenticated using (true);
create policy "authenticated users can read article hashtags"
  on public.article_hashtags for select to authenticated using (true);
create policy "authenticated users can read companies"
  on public.companies for select to authenticated using (true);
create policy "authenticated users can read article companies"
  on public.article_companies for select to authenticated using (true);

create policy "users can read their profile"
  on public.profiles for select to authenticated using ((select auth.uid()) = id);
create policy "users can update their profile"
  on public.profiles for update to authenticated
  using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

create policy "users can manage their feedback"
  on public.article_feedback for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "authenticated users can read timeline events"
  on public.timeline_events for select to authenticated using (true);

create policy "users can manage their saved filters"
  on public.saved_filters for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

-- 선별 결과는 로그인 사용자에게만 공개한다. 수집기/AI 쓰기는 서버 작업에서 수행한다.
create policy "authenticated users can read ai rankings"
  on public.ai_rankings for select to authenticated using (true);
create policy "authenticated users can read daily top news"
  on public.daily_top_news for select to authenticated using (true);
create policy "authenticated users can read active rules"
  on public.rule_versions for select to authenticated using (status = 'active');
create policy "authenticated users can read rule signals"
  on public.rule_signals for select to authenticated using (true);

-- Data API access is deliberately explicit because automatic table exposure is disabled.
grant usage on schema public to authenticated;
grant select on public.articles, public.article_celltypes, public.article_hashtags,
  public.companies, public.article_companies, public.ai_rankings,
  public.daily_top_news, public.rule_versions, public.rule_signals to authenticated;
grant select, insert, update, delete on public.article_feedback, public.saved_filters to authenticated;
grant select on public.timeline_events to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- 권역 보고서는 서버 API만 접근한다. service_role 키는 Vercel 서버 환경변수에만 둔다.
revoke all on public.regional_weekly_reports from anon, authenticated;
grant select, insert, update, delete on public.regional_weekly_reports to service_role;
